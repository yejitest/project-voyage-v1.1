export type WeatherConditionKey =
  | "sunny"
  | "partly-cloudy"
  | "cloudy"
  | "rainy"
  | "thunder"
  | "snowy"
  | "foggy";

export function WeatherConditionIcon({
  conditionKey,
  size = 16,
}: {
  conditionKey: WeatherConditionKey;
  size?: number;
}) {
  switch (conditionKey) {
    case "sunny":
      return <SunPixelIcon size={size} />;
    case "partly-cloudy":
      return <CloudSunPixelIcon size={size} />;
    case "cloudy":
      return <CloudPixelIcon size={size} />;
    case "rainy":
      return <RainPixelIcon size={size} />;
    case "thunder":
      return <ThunderPixelIcon size={size} />;
    case "snowy":
      return <SnowPixelIcon size={size} />;
    case "foggy":
      return <FogPixelIcon size={size} />;
    default:
      return <SunPixelIcon size={size} />;
  }
}

